import json
import re
from collections import Counter
import numpy as np
import torch
import torch.nn as nn

class Tokenizer(object):
    def __init__(self, args, device):
        self.ann_path = args.ann_path
        self.threshold = args.threshold
        self.dataset_name = args.dataset_name
        self.device = device
        self.pad_token_id = 0
        self.embedding_path = args.embedding_path

        # Vocab
        if self.dataset_name == 'iu_xray':
            self.clean_report = self.clean_report_iu_xray
        else:
            self.clean_report = self.clean_report_mimic_cxr
        self.ann = json.loads(open(self.ann_path, 'r').read())
        self.token2idx, self.idx2token = self.create_vocabulary()

        # ===== TOKEN EMBEDDINGS AB TOKENIZER MEIN HAIN =====
        self.text_embeddings = self._load_text_embeddings()
        self.tk_embed_dim = next(iter(self.text_embeddings.values())).shape[0]
        all_embs = torch.stack(list(self.text_embeddings.values()))
        self.avg_tk_emb = torch.mean(all_embs, dim=0).to(self.device)
        self.tk_proj = nn.Linear(self.tk_embed_dim, 768).to(self.device)

    def _load_text_embeddings(self):
        emb_dict = {}
        with open(self.embedding_path, 'r', encoding='utf-8') as f:
            for line in f:
                parts = line.strip().split()
                token = parts[0]
                emb = np.array(parts[1:], dtype=np.float32)
                emb_dict[token] = torch.tensor(emb, device=self.device, requires_grad=True)
        return emb_dict

    def get_token_embeddings(self, captions: torch.Tensor) -> torch.Tensor:
        batch_size, seq_len = captions.shape
        tk_embeds = torch.zeros((batch_size, seq_len, self.tk_embed_dim), device=self.device)

        for b in range(batch_size):
            for s in range(seq_len):
                token_id = captions[b, s].item()
                if token_id == self.pad_token_id:
                    token = '<pad>'
                else:
                    try:
                        token = self.get_token_by_id(token_id)
                    except KeyError:
                        token = '<unk>'

                if token in self.text_embeddings:
                    tk_embeds[b, s, :] = self.text_embeddings[token]
                else:
                    tk_embeds[b, s, :] = self.avg_tk_emb

        tk_embeds = self.tk_proj(tk_embeds)
        return tk_embeds

    # ==== Baaki sab same ====
    def create_vocabulary(self):
        total_tokens = []
        for example in self.ann['train']:
            tokens = self.clean_report(example['report']).split()
            for token in tokens:
                total_tokens.append(token)
        counter = Counter(total_tokens)
        vocab = [k for k, v in counter.items() if v >= self.threshold] + ['<unk>']
        vocab.sort()
        token2idx, idx2token = {}, {}
        for idx, token in enumerate(vocab):
            token2idx[token] = idx + 1
            idx2token[idx + 1] = token
        return token2idx, idx2token

    def clean_report_iu_xray(self, report):
        report_cleaner = lambda t: t.replace('..', '.').replace('..', '.').replace('..', '.').replace('1. ', '') \
            .replace('. 2. ', '. ').replace('. 3. ', '. ').replace('. 4. ', '. ').replace('. 5. ', '. ') \
            .replace(' 2. ', '. ').replace(' 3. ', '. ').replace(' 4. ', '. ').replace(' 5. ', '. ') \
            .strip().lower().split('. ')
        sent_cleaner = lambda t: re.sub('[.,?;*!%^&_+():-\[\]{}]', '', t.replace('"', '').replace('/', '').
                                        replace('\\', '').replace("'", '').strip().lower())
        tokens = [sent_cleaner(sent) for sent in report_cleaner(report) if sent_cleaner(sent) != []]
        report = ' . '.join(tokens) + ' .'
        return report

    def clean_report_mimic_cxr(self, report):
        report_cleaner = lambda t: t.replace('\n', ' ').replace('__', '_').replace('__', '_').replace('__', '_') \
            .replace('__', '_').replace('__', '_').replace('__', '_').replace('__', '_').replace('  ', ' ') \
            .replace('  ', ' ').replace('  ', ' ').replace('  ', ' ').replace('  ', ' ').replace('  ', ' ') \
            .replace('..', '.').replace('..', '.').replace('..', '.').replace('..', '.').replace('..', '.') \
            .replace('..', '.').replace('..', '.').replace('..', '.').replace('1. ', '').replace('. 2. ', '. ') \
            .replace('. 3. ', '. ').replace('. 4. ', '. ').replace('. 5. ', '. ').replace(' 2. ', '. ') \
            .replace(' 3. ', '. ').replace(' 4. ', '. ').replace(' 5. ', '. ') \
            .strip().lower().split('. ')
        sent_cleaner = lambda t: re.sub('[.,?;*!%^&_+():-\[\]{}]', '', t.replace('"', '').replace('/', '')
                                        .replace('\\', '').replace("'", '').strip().lower())
        tokens = [sent_cleaner(sent) for sent in report_cleaner(report) if sent_cleaner(sent) != []]
        report = ' . '.join(tokens) + ' .'
        return report

    def get_token_by_id(self, id):
        return self.idx2token[id]

    def get_id_by_token(self, token):
        if token not in self.token2idx:
            return self.token2idx['<unk>']
        return self.token2idx[token]

    def get_vocab_size(self):
        return len(self.token2idx)

    def __call__(self, report):
        tokens = self.clean_report(report).split()
        ids = []
        for token in tokens:
            ids.append(self.get_id_by_token(token))
        ids = [0] + ids + [0]
        return ids

    def decode(self, ids):
        txt = ''
        for i, idx in enumerate(ids):
            if idx > 0:
                if i >= 1:
                    txt += ' '
                txt += self.idx2token[idx]
            else:
                break
        return txt

    def decode_batch(self, ids_batch):
        out = []
        for ids in ids_batch:
            out.append(self.decode(ids))
        return out
